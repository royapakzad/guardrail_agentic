#!/usr/bin/env node
/**
 * generate-policy-criteria.mjs
 * -----------------------------
 * Regenerates src/lib/policyCriteria.generated.ts from the actual policy
 * files in ../config/*.txt (the parent repo's config directory).
 *
 * This replaces a hand-maintained duplicate list that drifted out of sync
 * with the real policy files (e.g. it was missing an entire criterion for
 * one humanitarian policy variant, silently hiding it from every
 * tool-requiring-criteria table in the dashboard). Instead of hand-editing
 * a list every time a policy changes, this script parses the same
 * "(potentially needs tool calls)" tagging convention the Python pipeline
 * uses (agentic_guardrails/policy_criteria.py) directly from the source
 * files, so the two can't drift apart again.
 *
 * Runs automatically via the `predev`/`prebuild` npm lifecycle hooks (see
 * package.json), so `npm run dev` / `npm run build` always regenerate this
 * file from whatever is currently in config/*.txt. The generated file is
 * still committed to git so a deploy environment without access to the
 * parent repo's config/ directory (e.g. a Vercel build with the monorepo
 * root directory set to annotation-platform/ and sibling files excluded)
 * still ships a working, if possibly stale, snapshot.
 *
 * Run manually with: npm run sync-policy-criteria
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CONFIG_DIR = path.resolve(__dirname, "..", "..", "config");
const OUT_FILE = path.resolve(__dirname, "..", "src", "lib", "policyCriteria.generated.ts");

// Mirrors agentic_guardrails/policy_criteria.py exactly — keep these two in
// sync if the tagging convention ever changes.
//
// \p{Nd} (Unicode "decimal digit number") rather than \d: Python's re module
// treats \d as any Unicode decimal digit by default (not just ASCII 0-9), so
// the Farsi policy files — numbered with Persian digits ۱ ۲ ۳ — parse fine
// on the Python side. Plain JS \d is ASCII-only and silently matched zero
// criteria in those files (they'd vanish from the generated output with no
// error). \p{Nd} plus the `u` flag closes that gap.
const HEADER_RE = /^(\p{Nd}+)\.\s+(.+?)\s*$/gmu;
const TOOL_TAG_RE =
  /\(\s*(?:potentially\s+)?(?:need|needs|require|requires)\s+tool(?:s)?(?:\s+call(?:s)?)?\s*\)/i;

function parsePolicyFile(text) {
  const criteria = [];
  for (const m of text.matchAll(HEADER_RE)) {
    const rawName = m[2].trim();
    const toolTagged = TOOL_TAG_RE.test(rawName);
    const name = rawName.replace(TOOL_TAG_RE, "").trim();
    criteria.push({ name, toolTagged });
  }
  return criteria;
}

function main() {
  if (!existsSync(CONFIG_DIR)) {
    console.warn(
      `[generate-policy-criteria] ${CONFIG_DIR} not found — skipping regeneration, ` +
        "keeping the last committed src/lib/policyCriteria.generated.ts as-is."
    );
    return;
  }

  const files = readdirSync(CONFIG_DIR).filter((f) => f.endsWith(".txt"));
  /** @type {Record<string, {name: string; toolTagged: boolean}[]>} */
  const byPolicy = {};

  for (const file of files) {
    const text = readFileSync(path.join(CONFIG_DIR, file), "utf-8");
    const criteria = parsePolicyFile(text);
    if (criteria.length === 0) continue; // not a criteria policy file (e.g. rubric.txt)
    const policyName = file.replace(/\.txt$/, "");
    byPolicy[policyName] = criteria;
  }

  const header =
    "// AUTO-GENERATED by scripts/generate-policy-criteria.mjs — do not edit by hand.\n" +
    "// Regenerated from ../config/*.txt on every `npm run dev` / `npm run build`\n" +
    "// (see the predev/prebuild scripts in package.json), and can be refreshed on\n" +
    "// demand with `npm run sync-policy-criteria`.\n" +
    "// Source of truth for the tagging convention: agentic_guardrails/policy_criteria.py\n\n";

  const body =
    "export const POLICY_CRITERIA_BY_POLICY: Record<string, { name: string; toolTagged: boolean }[]> = " +
    JSON.stringify(byPolicy, null, 2) +
    ";\n";

  writeFileSync(OUT_FILE, header + body);
  console.log(
    `[generate-policy-criteria] wrote ${Object.keys(byPolicy).length} polic${
      Object.keys(byPolicy).length === 1 ? "y" : "ies"
    } to ${path.relative(process.cwd(), OUT_FILE)}`
  );
}

main();
